"""Export out/<name>.npz to Luau.

    python export.py --name small

Writes
  ../luau/Weights.luau      ModuleScript (child of DrawRecognizer): labels, raster constants,
                            layer shapes and all weights as one base64 blob
                            (int8 weights, float32 per-channel scales, float32 biases per layer).
  ../luau/TestVectors.luau  Dev-only check data: a few test drawings' strokes with the Python
                            reference image checksums and logits (never shown to players).
  ../luau/DrawModelInfo.luau Public raster geometry/palette; no learned parameters.
  Weights and the inference module are installed server-side only.
"""
import argparse
import base64
import json
import os
import struct
import sys

import numpy as np
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from categories import CATEGORIES
import raster
import colour
from colour_raster import reference as colour_reference
from train import dequant, forward_plain

LUAU = os.path.join(HERE, "..", "luau")
DATA = os.path.join(HERE, "..", "data")


def lua_str_list(xs):
    return "{ " + ", ".join(json.dumps(x) for x in xs) + " }"


def write_model_info(out_dir, name, size, channels, box, radius):
    """Only geometry and palette may accompany the client preview."""
    lines = ['-- GENERATED by training/export.py; geometry/palette only, no weights.',
             'return table.freeze({', f'\tname = {json.dumps(name)},',
             f'\tsize = {size},', f'\tinputChannels = {channels},',
             f'\tbox = {box!r},', f'\tradius = {radius!r},']
    if channels == 4:
        lines += ['\townerTieEpsilon = 1e-12,', '\tpaletteNet = { ' + ', '.join(
            '{ ' + ', '.join(repr(float(v)) for v in rgb) + ' }' for rgb in colour.NET) + ' },']
    lines.append('})')
    with open(os.path.join(out_dir, 'DrawModelInfo.luau'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines)+'\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", default="small")
    ap.add_argument("--samples", type=int, default=8)
    ap.add_argument("--expanded", action="store_true")
    ap.add_argument("--out-dir", default=LUAU, help="directory for this model's Luau artifacts")
    ap.add_argument('--probes', action='store_true', help='include independent private stroke regressions in dev vectors')
    ap.add_argument('--extra-vectors',help='optional dev-only stroke vectors; never player-facing')
    a = ap.parse_args()
    z = np.load(os.path.join(HERE, "out", a.name + ".npz"))
    res = json.load(open(os.path.join(HERE, "out", a.name + ".json")))
    # The two original 32-class artifacts predate embedded label metadata. Their
    # ordering is preserved as the first 32 entries of the expanded vocabulary.
    labels = res.get("categories", CATEGORIES[:32])
    assert len(labels) == z["w4"].shape[0], "model and category list disagree"
    q = [(z[f"w{i}"], z[f"s{i}"], z[f"b{i}"]) for i in range(5)]
    channels = q[0][0].shape[1]
    z.close()
    size = res.get("size", 28)
    renderer = raster.Renderer(size)
    out_dir = a.out_dir
    torch.set_num_threads(4)

    blob = bytearray()
    specs = []
    for wi, s, b in q:
        nout = wi.shape[0]
        nper = int(np.prod(wi.shape[1:]))
        blob += wi.astype(np.int8).tobytes()
        blob += s.astype("<f4").tobytes()
        blob += b.astype("<f4").tobytes()
        if wi.ndim == 4:
            specs.append(f"{{ kind = \"conv\", nout = {nout}, nper = {nper}, cin = {wi.shape[1]}, pool = true, scaleInputs = {str(s.ndim == 2).lower()} }}")
        else:
            normalize = bool(res.get('feature_normalize')) and len(specs)==4
            specs.append(f"{{ kind = \"dense\", nout = {nout}, nper = {nper}, normalizeInput = {str(normalize).lower()} }}")
    b64 = base64.b64encode(bytes(blob)).decode()
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "Weights.luau"), "w", newline="\n") as f:
        f.write("--!nocheck\n-- GENERATED by training/export.py - do not edit.\n")
        f.write(f"-- Model '{a.name}': widths {res['widths']}, fc {res['fc']}, {res['params']} params, "
                f"int8 test top-1 {res['int8_top1']:.4f}, top-3 {res['int8_top3']:.4f}.\n")
        f.write("-- Trained on Google's Quick, Draw! dataset (CC BY 4.0).\n")
        if len(labels) > 270:
            f.write("-- Additional custom labels use hand-reviewed procedural doodles; synthetic accuracy is an upper bound.\n")
        if res.get('generated_data'):
            f.write("-- Also trained with offline FLUX.1-schnell outputs (Apache-2.0), filtered by frozen SigLIP; not player drawings.\n")
        f.write("return {\n")
        f.write(f"\tname = {json.dumps(a.name)},\n\tsize = {size},\n")
        f.write(f"\tinputChannels = {channels},\n")
        if res.get('feature_normalize'):
            f.write(f"\tqualityNormScale = {float(res['quality_norm_scale'])!r},\n")
        if channels == 4:
            f.write("\townerTieEpsilon = 1e-12,\n")
            f.write("\tpaletteNet = { " + ", ".join("{ " + ", ".join(repr(float(v)) for v in rgb) + " }" for rgb in colour.NET) + " },\n")
        f.write(f"\tlabels = {lua_str_list(labels)},\n")
        f.write(f"\tbox = {renderer.box!r},\n\tradius = {renderer.radius!r},\n")
        f.write("\tlayers = { " + ", ".join(specs) + " },\n")
        f.write("\tdata = table.concat({\n")
        for i in range(0, len(b64), 120):
            f.write(f"\t\t\"{b64[i:i + 120]}\",\n")
        f.write("\t}),\n")
        f.write("}\n")
    print("weights blob", len(blob), "bytes, base64", len(b64))
    write_model_info(out_dir, a.name, size, channels, renderer.box, renderer.radius)

    # test vectors
    corpus = res.get("corpus") or ("expanded" if a.expanded else "")
    # A training-only unattended export must not open held-out stroke files.
    if a.samples > 0:
        samples = json.load(open(os.path.join(DATA, corpus, "test_strokes.json")))
        step = max(1, len(samples) // a.samples)
        picked = samples[::step][: a.samples]
    else:
        picked = []
    if a.probes:
        from colour_probes import cases
        for c in cases():
            drawing=[[[p[0] for p in st],[p[1] for p in st]] for st in c['strokes']]
            colours=[v-1 for v in c['colours']] if c['colours'] else [0]*len(drawing)
            picked.append({'label':0,'drawing':drawing,'colours':colours})
    if a.extra_vectors:
        with open(a.extra_vectors,encoding='utf-8') as f:picked+=json.load(f)
    if channels == 4:
        # One per class plus geometric edge cases; all are dev-only, never rendered in UI.
        picked += [
            {'label':0,'drawing':[[[0,100],[50,50]],[[0,100],[50,50]]],'colours':[3,7]},
            {'label':0,'drawing':[[[0,100],[50,50]],[[100,0],[50,50]]],'colours':[3,7]},
            {'label':0,'drawing':[[[0,100],[0,100]],[[0,100],[100,0]]],'colours':[4,7]},
            {'label':0,'drawing':[[[],[]],[[0],[0]]],'colours':[3,5]},
            {'label':0,'drawing':[[[0],[0]],[[0],[0]]],'colours':[3,7]},
            {'label':0,'drawing':[[[0,100],[0,0]],[[0,100],[20,20]]],'colours':[3]},
        ]
    plain = dequant(q)
    # These are large generated data tables. Skip editor type inference on them;
    # Python export checks and runtime parity/shape checks validate their contents.
    lines = ["--!nocheck", "-- GENERATED by training/export.py. Dev-only: held-out test strokes + Python reference output.",
             "-- Never show these drawings to players.", "return {"]
    rng = np.random.default_rng(20261114)
    for sample_index, s in enumerate(picked):
        # Roblox/CLI vectors store point coordinates as float32. Derive the
        # reference from those exact values, including rotated generated paths,
        # rather than comparing vector-rounded inputs against float64 originals.
        s={**s,'drawing':[[np.asarray(xs,np.float32).astype(np.float64).tolist(),
                          np.asarray(ys,np.float32).astype(np.float64).tolist()] for xs,ys in s['drawing']]}
        img = renderer.render(s["drawing"])
        colours = None
        if channels == 4:
            img, owner = colour_reference(s['drawing'], size)
            if 'colours' in s: colours=s['colours']
            elif sample_index % 3 == 0: colours=[0]*len(s['drawing'])
            elif sample_index % 3 == 1:
                colours=colour.colourise(labels[s['label']],colour.stroke_ink(s['drawing']),rng)
                while not any(colours):colours=colour.colourise(labels[s['label']],colour.stroke_ink(s['drawing']),rng)
            else: colours=rng.integers(1,len(colour.PALETTE),len(s['drawing'])).tolist()
            complete=[colours[i] if i<len(colours) else 0 for i in range(len(s['drawing']))]
            image=colour.planes(img,owner,complete)
        else:image=img[None]
        x = torch.from_numpy(image).double()[None]
        with torch.no_grad():
            if res.get('feature_normalize'):
                from gacl import reference
                output, norm = reference(plain, x, normalize=True, details=True)
                lg = output[0].numpy()
            else:lg = forward_plain(plain, x)[0].numpy()
        strokes = "{ " + ", ".join("{ " + ", ".join(f"{float(xx)!r}, {float(yy)!r}" for xx, yy in zip(xs, ys)) + " }"
                                   for xs, ys in s["drawing"]) + " }"
        idx = np.arange(size * size)
        lines.append("\t{")
        lines.append(f"\t\tlabel = {s['label']},")
        lines.append(f"\t\tsize = {size},")
        if channels == 4:
            lines.append("\t\tcolours = { " + ", ".join(str(int(c)+1) for c in colours) + " },")
            sums=[float(p.sum()) for p in image]
            moments=[float((p.reshape(-1)*idx).sum()) for p in image]
            lines.append("\t\timageSums = { " + ", ".join(repr(v) for v in sums) + " },")
            lines.append("\t\timageMoments = { " + ", ".join(repr(v) for v in moments) + " },")
        lines.append(f"\t\tstrokes = {strokes},")
        lines.append(f"\t\timageSum = {float(img.sum())!r}, imageMoment = {float((img.reshape(-1) * idx).sum())!r},")
        lines.append("\t\tlogits = { " + ", ".join(repr(float(v)) for v in lg) + " },")
        if res.get('feature_normalize'):
            lines.append(f"\t\tfeatureNorm = {float(norm[0])!r},")
        lines.append("\t},")
    lines.append("}")
    with open(os.path.join(out_dir, "TestVectors.luau"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("test vectors", len(picked))


if __name__ == "__main__":
    main()
